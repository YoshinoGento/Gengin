def crop_copy(name, material):
    # Voxelize bodies for the ceremony only; leaf geometry keeps its authored silhouette.
    source=(ROOT/'project/Resources/farm'/(name+'.obj')).read_text(encoding='utf-8')
    if name in ('crop_turnip','crop_carrot','crop_tomato','crop_pumpkin'):
        mesh=Mesh(); append_crop(mesh,source,material)
        return save(mesh,name)
    lines=source.splitlines()
    normals=[tuple(map(float,line.split()[1:4])) for line in lines if line.startswith('vn ')]
    out=['# Original crop silhouette; UV-only ceremony daylight variant.']
    out += [line for line in lines if line.startswith(('v ','vn '))]
    faces=[]; uv_index=0
    for line in lines:
        if not line.startswith('f '): continue
        face=[]
        for item in line.split()[1:]:
            fields=item.split('/'); vertex=int(fields[0]); normal=int(fields[2])
            nx,ny,nz=normals[normal-1]
            u,v=uv_at(.5,.5,(-nx,ny,nz),material)
            out.append(f'vt {u:.7f} {v:.7f}'); uv_index+=1
            face.append(f'{vertex}/{uv_index}/{normal}')
        faces.append('f '+' '.join(face))
    assert faces and len(faces)<10000
    (OUT/(name+'.obj')).write_text('\n'.join(out+faces)+'\n',encoding='ascii')
    return len(faces)


def build():
    OUT.mkdir(parents=True,exist_ok=True)
    atlas(); signs()
    counts={'venue':save(scenery(),'venue'),**props()}
    for name,material in (('crop_turnip',18),('crop_turnip_leaves',19),('crop_carrot',16),
                          ('crop_carrot_leaves',19),('crop_tomato',17),('crop_tomato_stems',19),
                          ('crop_pumpkin',20),('crop_pumpkin_vines',19)):
        counts[name]=crop_copy(name,material)
    assert sum(counts.values()) < MAX_TRIANGLES
    (OUT/'manifest.json').write_text(json.dumps({'original':True,'triangles':counts,
        'lighting':'runtime directional shadow map; albedo atlas','cropCell':CROP_CELL,
        'maxTriangles':MAX_TRIANGLES,'paletteSize':[len(COLORS)*CELL,ROWS*CELL]},indent=2)+'\n',encoding='ascii')
    print(json.dumps(counts))


if __name__=='__main__':
    build()
