class Mesh(rural.Mesh):
    def triangle(self, points, uv, material, section):
        assert 0 <= material < len(COLORS)
        a = tuple(points[1][j]-points[0][j] for j in range(3))
        b = tuple(points[2][j]-points[0][j] for j in range(3))
        n = (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
        length = math.sqrt(sum(x*x for x in n))
        assert length > 1e-7 and all(math.isfinite(v) for p in points for v in p)
        self.triangles.append((points, uv, tuple(x/length for x in n), material, section))


def uv_at(u, v, normal, material):
    # Albedo only: lighting/shadows are evaluated in the engine, not twice in an atlas.
    shade = ROWS-1
    return ((material+.08+.84*u)/len(COLORS), 1-(shade+.08+.84*v)/ROWS)


def save(mesh, name, raw_uv=False):
    assert len(mesh.triangles) <= MAX_TRIANGLES
    lines = ['# Original geometry generated by generate_contest_ceremony.py', 's off']
    for points, uv, normal, material, _ in mesh.triangles:
        for j in (0,2,1):
            x,y,z = points[j]
            lines.append(f'v {-x:.6f} {y:.6f} {z:.6f}')
            u,v = (uv[j][0], 1-uv[j][1]) if raw_uv else uv_at(*uv[j], normal, material)
            lines.append(f'vt {u:.7f} {v:.7f}')
        lines.append(f'vn {-normal[0]:.6f} {normal[1]:.6f} {normal[2]:.6f}')
    for i in range(len(mesh.triangles)):
        lines.append('f '+' '.join(f'{3*i+j+1}/{3*i+j+1}/{i+1}' for j in range(3)))
    (OUT/(name+'.obj')).write_text('\n'.join(lines)+'\n',encoding='ascii')
    return len(mesh.triangles)


def atlas():
    im = Image.new('RGB',(len(COLORS)*CELL,ROWS*CELL))
    rng = random.Random(28102026)
    for material, base in enumerate(COLORS):
        for row in range(ROWS):
            shade = .78+.22*row/(ROWS-1)
            for y in range(CELL):
                for x in range(CELL):
                    grain = rng.uniform(-.025,.025)
                    if material == 4:
                        grain += .045*math.sin(y*.8+math.sin(x*.11))
                    if material == 3:
                        grain += .015*((x+y)%2)
                    if material == 5:
                        grain += .05*math.sin(y*.35+math.sin(x*.18))
                    im.putpixel((material*CELL+x,row*CELL+y),tuple(max(0,min(255,round(v*(shade+grain)))) for v in base))
    im.save(OUT/'palette.png',optimize=True)


def grass_blade(mesh, x, z, height, yaw, lean):
    # Closed tapered prism: both sides and the narrow edge receive physical lighting.
    c,s=math.cos(yaw),math.sin(yaw)
    local=((-0.035,0,-.009),(.035,0,-.009),(lean,height,-.009),
           (-.035,0,.009),(.035,0,.009),(lean,height,.009))
    points=tuple((x+px*c-pz*s,-.24+py,z+px*s+pz*c) for px,py,pz in local)
    for face in ((0,2,1),(3,4,5)):
        mesh.triangle(tuple(points[i] for i in face),((0,0),(.5,1),(1,0)),2,'grass')
    for face in ((0,1,4,3),(1,2,5,4),(2,0,3,5)):
        mesh.quad(tuple(points[i] for i in face),2,'grass')


