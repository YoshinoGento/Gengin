"""Generate an original, deterministic seamless rain bed; no external samples."""
import array
import hashlib
import json
import math
from pathlib import Path
import random
import wave

RATE = 24000
SECONDS = 6
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "project/Resources/farm/weather/audio"


def samples():
    count = RATE * SECONDS
    rng = random.Random(20261110)
    noise = [rng.uniform(-1, 1) for _ in range(count)]
    # Warm up the circular noise filter so the loop boundary has no reset transient.
    low = slow = 0.0
    bed = []
    for turn in range(2):
        for i, value in enumerate(noise):
            low += .22 * (value - low)
            slow += .018 * (value - slow)
            swell = .92 + .05 * math.sin(math.tau*i/count) + .03 * math.sin(3*math.tau*i/count)
            if turn:
                bed.append((low*.75 + slow*.45)*swell)
    # Small diffuse impacts, wrapped into the loop rather than cut at its ends.
    for _ in range(520):
        start = rng.randrange(count)
        amplitude = rng.uniform(.035, .12)
        for j in range(240):
            envelope = math.exp(-j/42) * min(j/4, 1)
            bed[(start+j) % count] += rng.uniform(-1, 1)*amplitude*envelope
    gain = .63 / max(abs(value) for value in bed)
    return array.array("h", (round(max(-1, min(1, value*gain))*32767) for value in bed))


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    pcm = samples().tobytes()
    target = OUTPUT / "rain.wav"
    with wave.open(str(target), "wb") as audio:
        audio.setnchannels(1)
        audio.setsampwidth(2)
        audio.setframerate(RATE)
        audio.writeframes(pcm)
    (OUTPUT / "manifest.json").write_text(json.dumps({
        "source": "Original procedural audio generated by tools/audio/generate_rain_audio.py",
        "external_samples": False, "sample_rate": RATE, "seconds": SECONDS,
        "channels": 1, "sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
        "loop": "Circular filtered noise and wrapped diffuse impacts; no fade-to-silence seam."
    }, indent=2)+"\n", encoding="utf-8")
    print(f"Generated {target.name}: {target.stat().st_size} bytes")


if __name__ == "__main__":
    main()
