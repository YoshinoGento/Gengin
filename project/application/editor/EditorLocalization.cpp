const char* editor::Localize(EditorLanguage language, std::string_view englishText) noexcept {
	if (language == EditorLanguage::English) {
		return englishText.data();
	}
	for (const LocalizedText& text : kJapaneseText) {
		if (text.english == englishText) {
			return reinterpret_cast<const char*>(text.japanese.data());
		}
	}
	return englishText.data();
}

const char* editor::GetEditorLanguageStorageName(EditorLanguage language) noexcept {
	return language == EditorLanguage::English ? "English" : "Japanese";
}

EditorLanguage editor::ParseEditorLanguage(std::string_view value) noexcept {
	return value == "English" ? EditorLanguage::English : EditorLanguage::Japanese;
}
